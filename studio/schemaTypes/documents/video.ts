import { PlayIcon } from '@sanity/icons'
import { defineArrayMember, defineField, defineType } from 'sanity'

type TimestampedItem = {
  startSeconds?: number
}

function validateTimestampOrder(value: unknown) {
  if (!Array.isArray(value)) {
    return true
  }

  let previous = -1

  for (const item of value as TimestampedItem[]) {
    if (typeof item?.startSeconds !== 'number') {
      continue
    }

    if (item.startSeconds <= previous) {
      return 'Start times must be unique and ordered from earliest to latest.'
    }

    previous = item.startSeconds
  }

  return true
}

export const video = defineType({
  name: 'video',
  title: 'Video',
  type: 'document',
  icon: PlayIcon,
  description:
    'Internal search lookup generated by the offline video ingestion pipeline.',
  fields: [
    defineField({
      name: 'id',
      title: 'Provider video ID',
      type: 'string',
      validation: (rule) => rule.required().max(240),
    }),
    defineField({
      name: 'url',
      title: 'Video URL',
      description: 'Must exactly match the URL stored on its lesson.',
      type: 'url',
      validation: (rule) => rule.required().uri({ scheme: ['http', 'https'] }),
    }),
    defineField({
      name: 'chapters',
      type: 'array',
      initialValue: [],
      of: [defineArrayMember({ type: 'videoChapter' })],
      validation: (rule) => rule.custom(validateTimestampOrder),
    }),
    defineField({
      name: 'chunks',
      title: 'Transcript chunks',
      type: 'array',
      of: [defineArrayMember({ type: 'videoChunk' })],
      validation: (rule) =>
        rule.required().min(1).custom(validateTimestampOrder),
    }),
  ],
  preview: {
    select: {
      title: 'id',
      url: 'url',
    },
    prepare({ title, url }) {
      return {
        title: title || 'Video',
        subtitle: url,
      }
    },
  },
})
